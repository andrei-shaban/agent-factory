-- ==============================================================================
-- vector (pgvector) — векторный поиск для RAG
-- ==============================================================================
-- Уже включён в 01-create-databases.sql. Дублируем для идемпотентности.
CREATE EXTENSION IF NOT EXISTS vector;

-- ==============================================================================
-- btree_gist — поддержка EXCLUDE-ограничений для интервальных типов
-- ==============================================================================
-- Требуется для таблицы rates: EXCLUDE USING gist (... daterange(...) WITH &&)
-- Предотвращает пересечение интервалов действия для одной позиции в договоре.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ==============================================================================
-- pg_trgm — триграммный поиск для нечёткого сопоставления строк
-- ==============================================================================
-- Используется для:
--   - нечёткого поиска по наименованиям позиций в ЕРР (similarity(), % оператор);
--   - построения GIN/GiST индексов для ускорения LIKE / ILIKE;
--   - сопоставления позиций актов с реестром при наличии опечаток, алиасов,
--     разных формулировок одной работы/материала.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

