#!/usr/bin/env bash
# ==============================================================================
# vm2/sandbox/deploy-toolsets.sh
# Сборка и доставка toolset-образов на выделенный rootless sandbox-демон
# Production Blueprint v5.3.1 — ВМ №2
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VM2_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="${VM2_DIR}/.env"

log() { printf '[%s] %s\n' "$1" "$2"; }
die() { log ERROR "$1"; exit 1; }

# ==============================================================================
# Проверки
# ==============================================================================
[[ -f "$ENV_FILE" ]] || die "Missing ${ENV_FILE}; run init_project.py first."

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

[[ -n "${SANDBOX_DOCKER_SOCKET:-}" ]] || die "SANDBOX_DOCKER_SOCKET not set in .env"
[[ -S "$SANDBOX_DOCKER_SOCKET" ]] || die "Sandbox socket does not exist: ${SANDBOX_DOCKER_SOCKET}"

# ==============================================================================
# Конфигурация
# ==============================================================================
TOOLSETS_DIR="${SCRIPT_DIR}/toolsets"
IMAGES_OUTPUT="${VM2_DIR}/worker/app/toolset-images.yaml"
PIP_INDEX_URL="${PYPI_MIRROR_URL:-http://vm1-pypiserver:8080/simple/}"

# Список toolset'ов для сборки (каталоги в toolsets/)
TOOLSETS=("excel")

# ==============================================================================
# Функции
# ==============================================================================
build_toolset() {
    local name="$1"
    local tag="factory/toolset-${name}:1.0.0"
    local toolset_dir="${TOOLSETS_DIR}/${name}"

    log INFO "Building toolset: ${name}"

    # Проверка наличия каталога toolset
    if [[ ! -d "$toolset_dir" ]]; then
        log WARN "Toolset directory not found: ${toolset_dir}, skipping"
        return 1
    fi

    # Подготовка контекста сборки
    local build_context=$(mktemp -d)
    trap "rm -rf '$build_context'" EXIT

    # Копируем Dockerfile и entrypoint
    cp "${SCRIPT_DIR}/Dockerfile.toolset" "${build_context}/Dockerfile"
    cp "${SCRIPT_DIR}/entrypoint.sh" "${build_context}/entrypoint.sh"
    cp "${SCRIPT_DIR}/requirements.txt" "${build_context}/requirements.txt"

    # Копируем код toolset
    mkdir -p "${build_context}/toolsets"
    cp -r "$toolset_dir" "${build_context}/toolsets/${name}"

    # Копируем wheelhouse (если есть, для air-gap)
    if [[ -d "${SCRIPT_DIR}/wheelhouse" ]]; then
        cp -r "${SCRIPT_DIR}/wheelhouse" "${build_context}/wheelhouse"
    fi

    # Сборка
    docker build \
        --build-arg PIP_INDEX_URL="${PIP_INDEX_URL}" \
        -t "$tag" \
        -f "${build_context}/Dockerfile" \
        "$build_context"

    log INFO "Built: ${tag}"
    echo "$tag"
}

load_to_sandbox_daemon() {
    local image="$1"

    log INFO "Loading ${image} to sandbox daemon..."
    docker save "$image" | DOCKER_HOST="unix://${SANDBOX_DOCKER_SOCKET}" docker load

    log INFO "Loaded: ${image}"
}

get_digest() {
    local image="$1"
    docker inspect --format='{{index .RepoDigests 0}}' "$image" 2>/dev/null || echo "$image"
}

# ==============================================================================
# Основная логика
# ==============================================================================
log INFO "Starting toolset deployment..."

# Очистка выходного файла
echo "# Toolset images (auto-generated by deploy-toolsets.sh)" > "$IMAGES_OUTPUT"
echo "# Do not edit manually; rerun deploy-toolsets.sh to update." >> "$IMAGES_OUTPUT"
echo "" >> "$IMAGES_OUTPUT"

success_count=0
fail_count=0

for toolset in "${TOOLSETS[@]}"; do
    if tag=$(build_toolset "$toolset"); then
        load_to_sandbox_daemon "$tag"

        digest=$(get_digest "$tag")
        echo "toolset_${toolset}: ${digest}" >> "$IMAGES_OUTPUT"

        log INFO "Deployed: ${toolset} → ${digest}"
        ((success_count++))
    else
        log ERROR "Failed to build toolset: ${toolset}"
        ((fail_count++))
    fi
done

log INFO "Deployment completed: ${success_count} succeeded, ${fail_count} failed"

if [[ $fail_count -gt 0 ]]; then
    exit 1
fi

log INFO "Toolset images written to: ${IMAGES_OUTPUT}"